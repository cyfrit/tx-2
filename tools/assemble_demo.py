#!/usr/bin/env python3
"""Rebuild the demo image using the upstream M4 cross-assembler listing."""
import pathlib
import hashlib
import argparse
import json
import re
import subprocess
import tx2tape

ROOT = pathlib.Path(__file__).resolve().parents[1]
build = ROOT / 'build'
build.mkdir(exist_ok=True)
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('source',nargs='?',default='programs/configured-copy.tx2as')
args=parser.parse_args()
source=(ROOT/args.source).resolve()
stem=source.stem
binary = ROOT / 'upstream/TX-2-simulator/target/debug/tx2m4as'
if not binary.exists():
    raise SystemExit('Build the reference assembler with: cargo build --locked --bin tx2m4as (in upstream/TX-2-simulator)')
result = subprocess.run([str(binary), '--list', '--output', str(build / (stem+'.tape')),
                         str(source)],
                        capture_output=True, text=True, check=True)
(build / (stem+'.list')).write_text(result.stdout + result.stderr)
words = {}
for high, low, address in re.findall(r'\|([0-7]{6}) ([0-7]{6})\|\s+([0-7]{1,6})', result.stdout):
    words[int(address, 8)] = int(high + low, 8)
if not words:
    raise SystemExit('Unexpected listing format: no complete image extracted')
source_digest = hashlib.sha256(source.read_bytes()).hexdigest()
revision = subprocess.check_output(['git','rev-parse','HEAD'],
                                  cwd=ROOT/'upstream/TX-2-simulator',text=True).strip()
image = '# Address (17 bits, hex), data (36 bits, hex); generated by assemble_demo.py\n'
image += f'# source_sha256 {source_digest}\n# assembler_repository_commit {revision}\n'
image += ''.join(f'{a:05x} {v:09x}\n' for a, v in sorted(words.items()))
(source.with_suffix('.hex')).write_text(image)
# Paper: preserve the original 20-word reader leader; relink blocks and
# recompute each 18-bit ring checksum in the tape tool, never inside the RTL.
raw=(build/(stem+'.tape')).read_bytes()
tape,blocks=tx2tape.relink(raw)
source.with_suffix('.tape').write_bytes(tape)
source.with_suffix('.tape.json').write_text(json.dumps({'source_sha256':source_digest,
    'raw_assembler_tape_sha256':hashlib.sha256(raw).hexdigest(),'reader_leader_words':20,
    'paper_lines':len(tape),'blocks':blocks},indent=2))
print(f'Assembled {len(words)} words using the upstream M4 assembler')
