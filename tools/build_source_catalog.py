#!/usr/bin/env python3
"""Generate the local TX-2 bibliography and readable coverage summary."""
import collections
import csv
import io
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
CAT = ROOT / 'references/catalog'
manifest = json.loads((CAT / 'manifest.json').read_text())
ocr = {x['id']: x for x in json.loads((CAT / 'archive-page-ocr.json').read_text())
       if x.get('status') != 'failed'}
for doc in manifest:
    if doc['id'] in ocr:
        doc.update(ocr[doc['id']])
(CAT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2))
pdfs = [x for x in manifest if x.get('filename', '').endswith('.pdf') and x['status'] == 'downloaded']
groups = collections.Counter(x['group'] for x in manifest)
summary = {
    'collection_date': '2026-11-10', 'pdf_files': len(pdfs),
    'pdf_pages': sum(x['pages'] for x in pdfs),
    'poster_images': sum(x.get('filename', '').endswith('.jpg') for x in manifest),
    'downloaded_bytes': sum(x.get('bytes', 0) for x in manifest),
    'distinct_sha256': len({x['sha256'] for x in manifest if 'sha256' in x}),
    'groups': dict(groups), 'archive_page_ocr_pairings': len(ocr),
    'cataloged_progress_report_links': len(json.loads((CAT / 'progress-report-inventory.json').read_text())),
    'note': 'Counts include alternative scans and editions of the same work; text availability is not a claim of OCR accuracy or complete reading.',
}
(CAT / 'collection-summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2))
fields = ['id', 'group', 'title', 'catalog_date', 'pages', 'bytes', 'sha256', 'path',
          'source_url', 'download_url', 'pages_with_text', 'archive_page_index_path']
with (CAT / 'bibliography.csv').open('w', newline='') as out:
    writer = csv.DictWriter(out, fields, extrasaction='ignore')
    writer.writeheader()
    writer.writerows(manifest)
labels = {
    'core': 'Manuals, early papers, Sketchpad, and programming',
    'user-memos': 'User memos and handbook variants',
    'hardware-and-precursors': 'Circuitry, storage, displays, and precursor designs',
    'early-progress-reports': 'Construction and operations reports, 1956–1962',
    'drawing-index': 'Historical drawing and slide index',
    'graphics-reports': 'Semiannual graphics research reports, 1965–1971',
    'peripherals': 'Lincoln Writer reports',
    'later-memory': '1971 thin-film memory report',
    'graphics-hardware': '1963 three-dimensional curve display report',
    'historical-source-listings': 'Sketchpad listings from the Computer History Museum',
    'reference-posters': 'System reference posters',
}
lines = [
    '# TX-2 Primary Sources', '',
    'Collection compiled on 2026-11-10. Generated by `tools/build_source_catalog.py`.', '',
    f"The collection includes **{summary['pdf_files']} PDFs with {summary['pdf_pages']:,} pages and {summary['poster_images']} posters**.",
    f"The scans and posters total {summary['downloaded_bytes'] / 1e6:.1f} MB, including alternate scans and revisions.",
    'The PDF count excludes modern catalog pages, metadata, and OCR attachments.', '',
    'See [Hardware Analysis](HARDWARE-READING.md) for circuit and timing analysis.', '',
    '## Scope and Provenance', '',
    'The scans come from Bitsavers mirrors, Internet Archive, RCS/RI, and the Computer History Museum.',
    'Each record includes source and download URLs, SHA-256, file size, page count, and text paths.',
    'Use the [JSON manifest](../references/catalog/manifest.json) or [CSV bibliography](../references/catalog/bibliography.csv).', '',
    'The collection includes the Bitsavers TX-2 and RCS/RI PDFs, Division 6 hardware documents,',
    'early progress reports, 13 semiannual graphics reports, and both parts of the Sketchpad listing.',
    'The [progress report inventory](../references/catalog/progress-report-inventory.json) records 82 catalog links.', '',
    '## Reading and Edition Notes', '',
    '- Alternate scans of the technical manuals supply missing figures and support cross-checking.',
    '- PDF text and Internet Archive OCR are stored separately. Eight supplemental OCR sets were matched by PDF MD5 and page count.',
    '- Use the scans to verify overbars, subscripts, timing phases, and wiring.',
    '- Catalog dates can describe the start of a compilation. `TX2-Memos-Display_196401` includes material from October 1964 and January 1965.',
    '- The 1963 user handbook scan includes replacement pages and a 1964 APEX configuration table.',
    '- Internet Archive metadata dated two 1958 memos to 1919. Use dates printed in the documents.', '',
    'Search examples:', '',
    '```sh',
    "python3 tools/search_sources.py 'memory overlap' --source LM-44v2 --limit 5",
    "python3 tools/search_sources.py 'CONFIGURATION|FRACTURE' --source TX-2_TechManVol2 --limit 10",
    '```', '',
    'Search results use physical PDF page numbers. Use the scan to locate printed page numbers.', '',
]
for group in labels:
    selected = sorted([x for x in manifest if x['group'] == group], key=lambda x: x['id'])
    if not selected:
        continue
    lines += ['## ' + labels[group], '', '| Local scan | Pages | Searchable text | Source |',
              '| --- | ---: | --- | --- |']
    for doc in selected:
        title = str(doc.get('title', doc['id'])).replace('|', '/')
        path = '../' + doc['path']
        if doc.get('archive_page_index_path'):
            text_link = f"[Internet Archive OCR](../{doc['archive_page_text_path']})"
        elif doc.get('pages_with_text', 0):
            text_link = f"[PDF text](../{doc['text_path']})"
        else:
            text_link = 'Image'
        lines.append(f"| [{title}]({path}) | {doc.get('pages', 'Image')} | {text_link} | [Source]({doc['source_url']}) |")
    lines += ['']
lines += [
    '## Outstanding Sources', '',
    '| Material | Archival lead |',
    '| --- | --- |',
    '| TX-2 Introductory Notes by A. Vanderburgh, 1959-02-24 | UMN/CBI 63, Box 8, TX-2 Materials 1959–1960 |',
    '| The New Skip-on-Index Instruction by J. M. Frankovich, 1960-02-04 | UMN/CBI 61, Box 7, Lincoln Labs materials |',
    '| Engineering drawings and change orders | Drawing numbers in the 1957 drawing and slide index |',
    '| Magnetic tape and plotter operating manuals | Partial coverage in the tape report and peripheral documentation |',
    '| 1963 wiring and field modifications | Original manuals and period memos |',
    '| Clear Sketchpad listings and original machine-readable tape | Computer History Museum listing scans with indistinct subscripts and characters |', '',
    'Collection tools require Python 3, PyMuPDF, Beautiful Soup, and aria2c:', '',
    '```sh', 'python3 tools/collect_primary_sources.py', 'python3 tools/add_archive_page_ocr.py',
    'python3 tools/build_source_catalog.py', '```', '',
]
(ROOT / 'docs/PRIMARY-SOURCES.md').write_text('\n'.join(lines), encoding='utf-8')
print(json.dumps(summary, ensure_ascii=False, indent=2))
