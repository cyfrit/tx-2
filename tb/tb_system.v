`timescale 1ns/1ps
`default_nettype none
module tb_system;
    reg clk=0;
    always #5 clk=~clk;
    reg reset=1, start=0;
    reg [16:0] start_address=0;
    wire running;
    wire [3:0] fault,overflow_flags;
    reg host_request=0, host_write=0;
    reg [16:0] host_address=0;
    reg [35:0] host_write_data=0;
    wire host_ready;
    wire [35:0] host_read_data;
    wire [1:0] host_error;
    wire retire;
    wire [16:0] retire_address, program_counter, operand_address;
    wire [35:0] retire_instruction, a,b,c,d,e;
    reg debug_override=0;
    reg [5:0] debug_x_select=0;
    reg [4:0] debug_f_select=0;
    wire [5:0] debug_index_address = debug_override ? debug_x_select : retire_instruction[23:18];
    wire [4:0] debug_configuration_address = debug_override ? debug_f_select : retire_instruction[34:30];
    wire [17:0] debug_index_data;
    wire [8:0] debug_configuration_data;
    reg [293:0] expected_trace;
    wire [293:0] actual_trace = {retire_address,retire_instruction,program_counter,
                               operand_address,a,b,c,d,e,debug_index_data,debug_configuration_data};
    reg [16:0] image_address;
    reg [35:0] image_data;
    reg [8:0] expected_f;
    reg [1023:0] header;
    integer fd, trace_fd, actual_fd, status, cycles, retired, checks=0, i;
    integer opcode_count;
    reg [63:0] executed_opcodes=0;
    tx2_system dut (.*);
    always @(negedge clk) if (retire) executed_opcodes[retire_instruction[29:24]]=1;

    function [35:0] ins;
        input h;
        input [4:0] cf;
        input [5:0] op, j;
        input defer;
        input [16:0] address;
        begin ins = {h,cf,op,j,defer,address}; end
    endfunction

    task reset_core;
        begin
            @(negedge clk); reset=1; start=0; host_request=0; debug_override=0;
            repeat(3) @(negedge clk);
            reset=0;
        end
    endtask
    task transfer;
        input writing;
        input [16:0] address;
        input [35:0] value;
        input [1:0] expected_error;
        input check_data;
        input [35:0] expected_data;
        integer waits;
        begin
            @(negedge clk);
            host_request=1; host_write=writing; host_address=address; host_write_data=value;
            waits=0;
            @(negedge clk);
            while (!host_ready && waits<30) begin @(negedge clk); waits=waits+1; end
            if (!host_ready || host_error !== expected_error)
                $fatal(1,"Host transaction failed at %o: error=%0d",address,host_error);
            if (check_data && host_read_data !== expected_data)
                $fatal(1,"Memory mismatch at %o: got %o expected %o",address,host_read_data,expected_data);
            host_request=0;
            checks=checks+1;
        end
    endtask
    task put;
        input [16:0] address;
        input [35:0] value;
        begin transfer(1,address,value,0,0,0); end
    endtask
    task launch;
        input [16:0] address;
        begin
            @(negedge clk); start_address=address; start=1;
            @(negedge clk); start=0;
            if (!running) $fatal(1,"Core did not start");
        end
    endtask
    task finish_run;
        input [3:0] expected_fault;
        input integer expected_retired;
        begin
            cycles=0; retired=0;
            while (fault==0 && cycles<20000) begin
                @(negedge clk); cycles=cycles+1;
                if (retire) retired=retired+1;
            end
            if (running || fault !== expected_fault || retired != expected_retired)
                $fatal(1,"Bad stop: fault=%0d retired=%0d expected=%0d",fault,retired,expected_retired);
            checks=checks+1;
        end
    endtask

    initial begin
        reset_core;
        // Load the exact image generated by the upstream M4 assembler.
        fd=$fopen("programs/configured-copy.hex","r");
        if (!fd) $fatal(1,"Missing program image");
        repeat(3) status=$fgets(header,fd);
        status=$fscanf(fd,"%h %h\n",image_address,image_data);
        while (status==2) begin
            put(image_address,image_data);
            status=$fscanf(fd,"%h %h\n",image_address,image_data);
        end
        $fclose(fd);
        trace_fd=$fopen("build/demo.trace.hex","r");
        actual_fd=$fopen("build/demo.actual.trace.hex","w");
        if (!trace_fd || !actual_fd) $fatal(1,"Cannot open trace files");
        launch(17'o100);
        cycles=0; retired=0;
        while (fault==0 && cycles<20000) begin
            @(negedge clk); cycles=cycles+1;
            if (retire) begin
                status=$fscanf(trace_fd,"%h\n",expected_trace);
                if (status!=1 || actual_trace !== expected_trace) begin
                    $display("PC=%o IR=%o P=%o Q=%o A=%o B=%o C=%o D=%o E=%o X=%o F=%o",
                        retire_address,retire_instruction,program_counter,operand_address,a,b,c,d,e,
                        debug_index_data,debug_configuration_data);
                    $display("actual  = %h\nexpected= %h",actual_trace,expected_trace);
                    $fatal(1,"Architectural trace mismatch at retirement %0d",retired);
                end
                $fdisplay(actual_fd,"%074h",actual_trace);
                retired=retired+1;
            end
        end
        status=$fscanf(trace_fd,"%h\n",expected_trace);
        if (running || fault!==1 || retired!=52 || status==1)
            $fatal(1,"Demo did not finish exactly at its undefined opcode");
        $fclose(trace_fd); $fclose(actual_fd);
        $display("PASS: M4 program, %0d instruction retirements matched reference state",retired);

        // Compare every changed RAM word, then all 32 F-memory entries.
        fd=$fopen("build/demo.memory.hex","r");
        status=$fscanf(fd,"%h %h\n",image_address,image_data);
        while (status==2) begin
            transfer(0,image_address,0,0,1,image_data);
            status=$fscanf(fd,"%h %h\n",image_address,image_data);
        end
        $fclose(fd);
        debug_override=1;
        fd=$fopen("build/demo.f-memory.hex","r");
        for (i=0;i<32;i=i+1) begin
            debug_f_select=i[4:0]; #1;
            status=$fscanf(fd,"%h\n",expected_f);
            if (status!=1 || debug_configuration_data !== expected_f)
                $fatal(1,"F-memory mismatch index=%o",i);
            checks=checks+1;
        end
        $fclose(fd);
        transfer(0,17'o210000,0,1,0,0);
        transfer(1,17'o377740,36'o123,2,0,0);
        transfer(0,17'o377740,0,0,1,36'o760342340000);
        put(17'o177777,36'o123456701234);
        transfer(0,17'o177777,0,0,1,36'o123456701234);
        put(17'o207777,36'o701234567012);
        transfer(0,17'o207777,0,0,1,36'o701234567012);

        // The real plugboard executes eight SPGs then two SKXs and stops
        // at the first not-yet-supported I/O instruction, not at fake I/O.
        reset_core;
        launch(17'o377750);
        finish_run(6,10);
        if (program_counter!==17'o377763) $fatal(1,"Wrong plugboard stop address");
        debug_override=1; debug_f_select=1; debug_x_select=6'o52; #1;
        if (debug_configuration_data!==9'o340 || debug_index_data!==18'o377763)
            $fatal(1,"Plugboard did not initialize F/X correctly");
        debug_x_select=6'o54; #1;
        if (debug_index_data!==18'o777754) $fatal(1,"Wrong negative reader count");
        $display("PASS: original plugboard executes 10 instructions up to IOS");

        reset_core;
        launch(17'o210000);
        finish_run(3,0);

        // A failed write never retires or applies the ultimate E copy.
        reset_core;
        put(17'o100,ins(0,0,6'o24,0,0,17'o404));
        put(17'o101,ins(0,0,6'o34,0,0,17'o377740));
        launch(17'o100); finish_run(4,1);
        if (a!==36'o111222333444 || e!==a) $fatal(1,"Fault caused partial register commit");
        transfer(0,17'o377740,0,0,1,36'o760342340000);

        // Dismiss and unsupported SKX configurations fail explicitly.
        reset_core;
        put(17'o100,ins(0,5'o20,6'o05,0,0,17'o101));
        launch(17'o100); finish_run(2,0);
        reset_core;
        put(17'o100,ins(0,5'o02,6'o12,1,0,17'o1));
        launch(17'o100); finish_run(2,0);

        // Two deferred levels, a pointer-local index, and original J.
        reset_core;
        put(17'o100,ins(0,0,6'o12,1,0,17'o3));
        put(17'o101,ins(0,0,6'o12,2,0,17'o2));
        put(17'o102,ins(0,0,6'o24,1,1,17'o200));
        put(17'o103,0);
        put(17'o200,ins(0,0,0,2,1,17'o210));
        put(17'o212,ins(0,0,0,0,0,17'o220));
        put(17'o223,36'o654321012345);
        launch(17'o100); finish_run(1,3);
        if (a!==36'o654321012345 || e!==a || operand_address!==17'o223)
            $fatal(1,"Chained indexed deferred address failed");

        // Both signed zeros must be excluded from JPX/JNX predicates.
        reset_core;
        put(17'o100,ins(0,1,6'o12,1,0,0));
        put(17'o101,ins(1,1,6'o06,1,0,0));
        put(17'o102,ins(0,1,6'o12,1,0,0));
        put(17'o103,ins(1,5'o36,6'o07,1,0,0));
        put(17'o104,0);
        launch(17'o100); finish_run(1,4);
        debug_override=1; debug_x_select=1; #1;
        if (debug_index_data!==18'o777776 || e!==0)
            $fatal(1,"Signed zero loop test failed");

        // AUX(+0,+0) preserves +0; DPX must NOT index its destination by Xj.
        reset_core;
        put(17'o100,ins(0,0,6'o10,1,0,17'o200));
        put(17'o101,ins(0,0,6'o16,1,0,17'o201));
        put(17'o102,0); put(17'o200,0); put(17'o201,0);
        launch(17'o100); finish_run(1,2);
        debug_override=1; debug_x_select=1; #1;
        if (debug_index_data!==0) $fatal(1,"AUX incorrectly changed +0 to -0");
        transfer(0,17'o201,0,0,1,0);

        reset_core;
        put(17'o100,ins(0,1,6'o12,1,0,0));
        put(17'o101,ins(0,0,6'o10,1,0,17'o200));
        put(17'o102,ins(0,0,6'o16,1,0,17'o201));
        put(17'o103,0);
        launch(17'o100); finish_run(1,3);
        transfer(0,17'o201,0,0,1,36'o777777777777);

        reset_core;
        put(17'o100,ins(0,0,6'o12,1,0,17'o4));
        put(17'o101,ins(0,0,6'o16,1,0,17'o201));
        put(17'o102,0); put(17'o201,0); put(17'o205,36'o123);
        launch(17'o100); finish_run(1,2);
        transfer(0,17'o201,0,0,1,36'o4);
        transfer(0,17'o205,0,0,1,36'o123);

        reset_core;
        put(17'o100,ins(0,0,6'o12,1,0,0));
        put(17'o101,ins(1,0,6'o06,1,0,0));
        put(17'o102,0);
        launch(17'o100); finish_run(1,2);
        debug_override=1; debug_x_select=1; #1;
        if (debug_index_data!==18'o777777) $fatal(1,"JPX zero sum was not -0");

        reset_core;
        put(17'o100,ins(0,0,6'o12,0,0,17'o7));
        put(17'o101,ins(0,0,6'o11,0,0,17'o404));
        put(17'o102,ins(0,0,6'o16,0,0,17'o201));
        put(17'o103,0);
        launch(17'o100); finish_run(1,3);
        debug_override=1; debug_x_select=0; #1;
        if (debug_index_data!==0) $fatal(1,"X0 was modified");
        transfer(0,17'o201,0,0,1,0);

        reset_core;
        put(17'o100,ins(0,0,6'o67,0,0,17'o200));
        launch(17'o100); finish_run(6,0);

        // Cover STC and both writable and hardwired-zero SPF destinations.
        reset_core;
        put(17'o100,ins(0,0,6'o26,0,0,17'o404));
        put(17'o101,ins(0,0,6'o36,0,0,17'o202));
        put(17'o102,ins(0,7,6'o21,0,0,17'o200));
        put(17'o103,ins(0,0,6'o21,0,0,17'o201));
        put(17'o104,0);
        put(17'o200,36'o321); put(17'o201,36'o777777777777); put(17'o202,0);
        launch(17'o100); finish_run(1,4);
        transfer(0,17'o202,0,0,1,36'o111222333444);
        debug_override=1; debug_f_select=7; #1;
        if (debug_configuration_data!==9'o321 || e!==36'o777777777777)
            $fatal(1,"SPF did not write selected quarter or update E");
        debug_f_select=0; #1;
        if (debug_configuration_data!==0) $fatal(1,"SPF modified F0");

        // JPQ preserves the last data reference and the return point in E.
        reset_core;
        put(17'o100,ins(0,0,6'o24,0,0,17'o404));
        put(17'o101,ins(0,5'o14,6'o05,0,0,17'o103));
        put(17'o103,0);
        launch(17'o100); finish_run(1,2);
        if (e!==36'o000404000102 || operand_address!==17'o404)
            $fatal(1,"JMP lost last Q or return P");

        opcode_count=0;
        for (i=0;i<64;i=i+1) if (executed_opcodes[i]) opcode_count=opcode_count+1;
        if (opcode_count!=19) $fatal(1,"Incomplete opcode execution coverage: %0d",opcode_count);
        $display("PASS: all %0d supported opcode numbers executed; bitmap=%h",opcode_count,executed_opcodes);

        $display("PASS: %0d host/register/fault checks plus chained defer and signed-zero tests",checks);
        $finish;
    end
    initial begin #2000000; $fatal(1,"System test timed out"); end
endmodule
`default_nettype wire
